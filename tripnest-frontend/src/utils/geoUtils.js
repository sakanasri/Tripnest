// Check local storage geocoding cache
function getGeocodeCache() {
    try {
        const cached = localStorage.getItem("tripnest_geocache");
        return cached ? JSON.parse(cached) : {};
    } catch {
        return {};
    }
}

function saveGeocodeCache(name, coords) {
    try {
        const cache = getGeocodeCache();
        cache[name.trim().toLowerCase()] = coords;
        localStorage.setItem("tripnest_geocache", JSON.stringify(cache));
    } catch {
        // storage quota or error
    }
}

/**
 * Synchronous lookup for immediate map pin placement
 */
export function getCoordinatesSync(cityName, fallback = null) {
    if (!cityName || !cityName.trim()) {
        return fallback || [13.0827, 80.2707]; // Default to Chennai instead of Delhi
    }

    const clean = cityName.trim().toLowerCase();

    // 1. Exact or partial match in CITY_COORDINATES
    for (const [key, coords] of Object.entries(CITY_COORDINATES)) {
        if (clean === key || clean.includes(key) || key.includes(clean)) {
            return coords;
        }
    }

    // 2. Check localStorage geocode cache
    const cache = getGeocodeCache();
    if (cache[clean]) {
        return cache[clean];
    }

    // 3. Fallback
    return fallback || [13.0827, 80.2707];
}

/**
 * Asynchronous dynamic geocoding using OpenStreetMap Nominatim
 * Resolves exact coordinates for any town, street, village or city in the world
 */
export async function resolveCoordinatesAsync(cityName, fallback = null) {
    if (!cityName || !cityName.trim()) {
        return fallback || [13.0827, 80.2707];
    }

    const clean = cityName.trim().toLowerCase();

    // 1. Check local static dictionary first
    for (const [key, coords] of Object.entries(CITY_COORDINATES)) {
        if (clean === key || clean.includes(key) || key.includes(clean)) {
            return coords;
        }
    }

    // 2. Check geocode cache
    const cache = getGeocodeCache();
    if (cache[clean]) {
        return cache[clean];
    }

    // 3. Query OpenStreetMap Nominatim Geocoding API
    try {
        const query = encodeURIComponent(cityName.trim());
        const res = await fetch(`https://nominatim.openstreetmap.org/search?format=json&q=${query}&limit=1`, {
            headers: {
                "Accept-Language": "en",
            },
        });
        if (res.ok) {
            const data = await res.json();
            if (data && data.length > 0) {
                const lat = parseFloat(data[0].lat);
                const lon = parseFloat(data[0].lon);
                if (!isNaN(lat) && !isNaN(lon)) {
                    const coords = [lat, lon];
                    saveGeocodeCache(clean, coords);
                    return coords;
                }
            }
        }
    } catch (err) {
        console.warn("Dynamic geocoding lookup failed for", cityName, err);
    }

    return fallback || [13.0827, 80.2707];
}
